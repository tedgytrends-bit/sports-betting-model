#!/usr/bin/env python3
"""Grade paired baseline vs player-injury predictions against historical lines.

Research only. Uses the paired predictions generated by
chronological_player_injury_backtest.py. Does not modify official projections.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

from model import load_schedule_data

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data" / "player_injury_backtests"

ATS_THRESHOLDS = (1.5, 2.5, 3.5)
TOTAL_THRESHOLDS = (1.5, 2.5, 3.5)
WIN_PROFIT = 100.0 / 110.0  # One unit risked at -110.


def latest_paired_file() -> Path:
    files = sorted(DATA_DIR.glob("player_injury_paired_predictions_*.csv"))
    if not files:
        raise FileNotFoundError(
            "No paired prediction CSV found. Run the chronological player "
            "injury backtest workflow first."
        )
    return files[-1]


def grade_market(
    frame: pd.DataFrame,
    model_name: str,
    market: str,
    threshold: float,
) -> dict:
    """Grade one model's ATS or totals picks at a fixed edge threshold."""
    if market == "ATS":
        edge = frame[f"{model_name}_home_margin"] + frame["spread_line"]
        actual = frame["actual_home_margin"] + frame["spread_line"]
    elif market == "TOTAL":
        edge = frame[f"{model_name}_total"] - frame["total_line"]
        actual = frame["actual_total"] - frame["total_line"]
    else:
        raise ValueError(f"Unknown market: {market}")

    valid = edge.notna() & actual.notna()
    edge = edge[valid]
    actual = actual[valid]

    selected = edge.abs() >= threshold
    edge = edge[selected]
    actual = actual[selected]

    wins = int(((np.sign(edge) == np.sign(actual)) & actual.ne(0)).sum())
    losses = int(((np.sign(edge) != np.sign(actual)) & actual.ne(0)).sum())
    pushes = int(actual.eq(0).sum())
    bets = wins + losses + pushes
    decisions = wins + losses

    profit = wins * WIN_PROFIT - losses
    risked = float(bets)

    return {
        "model": model_name,
        "market": market,
        "edge_threshold_points": threshold,
        "bets": bets,
        "wins": wins,
        "losses": losses,
        "pushes": pushes,
        "decisions_excluding_pushes": decisions,
        "win_rate_excluding_pushes": (
            wins / decisions if decisions else None
        ),
        "net_units_at_minus_110": round(profit, 4),
        "units_risked_including_pushes": risked,
        "roi_percent": (
            round(100.0 * profit / risked, 2) if risked else None
        ),
    }


def grade_all(frame: pd.DataFrame) -> tuple[list[dict], list[dict]]:
    overall = []
    by_season = []

    for market, thresholds in (
        ("ATS", ATS_THRESHOLDS),
        ("TOTAL", TOTAL_THRESHOLDS),
    ):
        for threshold in thresholds:
            for model_name in ("baseline", "injury"):
                overall.append(
                    grade_market(frame, model_name, market, threshold)
                )

                for season, season_frame in frame.groupby("season"):
                    result = grade_market(
                        season_frame, model_name, market, threshold
                    )
                    result["season"] = int(season)
                    by_season.append(result)

    return overall, by_season


def self_test() -> None:
    """Small deterministic grading checks for signs, wins, losses, and pushes."""
    sample = pd.DataFrame({
        "baseline_home_margin": [7.0, -7.0, 3.0],
        "injury_home_margin": [7.0, -7.0, 3.0],
        "baseline_total": [50.0, 40.0, 45.0],
        "injury_total": [50.0, 40.0, 45.0],
        "actual_home_margin": [7.0, -7.0, 3.0],
        "actual_total": [50.0, 40.0, 45.0],
        "spread_line": [-3.0, 3.0, -3.0],
        "total_line": [47.0, 43.0, 45.0],
    })

    # ATS: first two cover; third is a push.
    ats = grade_market(sample, "baseline", "ATS", 1.0)
    assert (ats["wins"], ats["losses"], ats["pushes"]) == (2, 0, 1)

    # Totals: first two are pushes against the selected edge direction;
    # third is a push at the line. No non-push decision should be fabricated.
    totals = grade_market(sample, "baseline", "TOTAL", 1.0)
    assert totals["bets"] == 0

    print("Betting-grade self-tests passed.")


def main() -> None:
    self_test()

    paired_path = latest_paired_file()
    paired = pd.read_csv(paired_path)

    required = {
        "game_id", "season", "home_score", "away_score",
        "pred_home_score_baseline", "pred_away_score_baseline",
        "pred_home_score_injury", "pred_away_score_injury",
    }
    missing = required - set(paired.columns)
    if missing:
        raise ValueError(
            f"Paired prediction file is missing columns: {sorted(missing)}"
        )

    if paired["game_id"].duplicated().any():
        raise ValueError("Duplicate game IDs found in paired predictions.")

    schedule = load_schedule_data()
    line_columns = ["game_id", "spread_line", "total_line"]
    missing_lines = set(line_columns) - set(schedule.columns)
    if missing_lines:
        raise ValueError(
            f"Schedule is missing market columns: {sorted(missing_lines)}"
        )

    lines = schedule[line_columns].drop_duplicates("game_id")
    if lines["game_id"].duplicated().any():
        raise ValueError("Duplicate game IDs found in market-line data.")

    frame = paired.merge(
        lines, on="game_id", how="left", validate="one_to_one"
    )

    frame["baseline_total"] = (
        frame["pred_home_score_baseline"]
        + frame["pred_away_score_baseline"]
    )
    frame["injury_total"] = (
        frame["pred_home_score_injury"]
        + frame["pred_away_score_injury"]
    )
    frame["baseline_home_margin"] = (
        frame["pred_home_score_baseline"]
        - frame["pred_away_score_baseline"]
    )
    frame["injury_home_margin"] = (
        frame["pred_home_score_injury"]
        - frame["pred_away_score_injury"]
    )
    frame["actual_total"] = frame["home_score"] + frame["away_score"]
    frame["actual_home_margin"] = frame["home_score"] - frame["away_score"]

    overall, by_season = grade_all(frame)

    report = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "RESEARCH_ONLY_NOT_OFFICIAL",
        "paired_prediction_file": paired_path.name,
        "paired_games": int(len(frame)),
        "games_with_spread_line": int(frame["spread_line"].notna().sum()),
        "games_with_total_line": int(frame["total_line"].notna().sum()),
        "pricing_assumption": (
            "Standard -110 odds for every wager; actual historical sportsbook "
            "prices are not available in this calculation."
        ),
        "roi_method": (
            "One unit risked per bet; winning profit is 100/110 units, "
            "loss is -1 unit, push is 0. ROI denominator includes pushed stakes."
        ),
        "spread_convention": (
            "The schedule spread_line is the home-team handicap. "
            "ATS edge = predicted home margin + spread_line."
        ),
        "total_convention": (
            "Totals edge = predicted total - market total. "
            "Positive means over; negative means under."
        ),
        "overall_results": overall,
        "season_results": by_season,
        "limitations": [
            "Historical market lines are schedule-source lines, not verified "
            "Bovada or DraftKings prices.",
            "All wagers are priced at assumed -110 odds.",
            "This is a historical research comparison, not an official model record.",
            "Historical injury timestamps do not prove public availability "
            "at the exact timestamp.",
            "Threshold results are sensitivity analysis and should not be "
            "used to select a profitable threshold after seeing results.",
        ],
    }

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    report_path = DATA_DIR / f"player_injury_betting_report_{stamp}.json"
    results_path = DATA_DIR / f"player_injury_betting_results_{stamp}.csv"

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    pd.DataFrame(overall).to_csv(results_path, index=False)

    print(json.dumps(report, indent=2))
    print(f"Saved report: {report_path}")
    print(f"Saved results: {results_path}")


if __name__ == "__main__":
    main()
